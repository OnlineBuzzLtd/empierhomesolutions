/**
 * READ-ONLY audit: which CRM records look like test data?
 *
 * Produces the candidate list a human approves BEFORE anything is deleted.
 * It makes no writes, sends no messages, and calls no third-party provider.
 *
 * Why a review step rather than "delete where is_test = true": the flag is not
 * trustworthy on its own.
 *   - Public webchat used to set `is_test` from `/\btest\b/i` over the whole
 *     message, so a genuine customer asking for a "gas safety test" was tagged.
 *     (Fixed 2026-08-19, but rows written before that keep the bad tag.)
 *   - Demo and channel-test rows created before the flag existed are untagged.
 *   - Live channel-test scripts generate recognisable personas / emails that no
 *     flag records at all.
 * So the script gathers EVIDENCE per row and lets a person decide.
 *
 * Run:
 *   node scripts/ops/audit-test-crm-records.mjs
 *
 * Options (env):
 *   TENANT_ID=<uuid>   tenant to audit (default: Empire Home Solutions)
 *   SINCE=2026-01-01   only rows created on/after this date
 *   JSON=1             emit the full candidate list as JSON on stdout
 *   OUT=<path>         also write the JSON candidate list to this file
 *
 * Output is a per-table summary plus, for each candidate, the reasons it was
 * flagged. Names/emails/phones are shown MASKED — this is production PII and
 * the point of the review is to judge the evidence, not to read the data.
 */

import fs from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { requireCrmScriptConfig } from "../crm-env.mjs";

const TENANT_ID = process.env.TENANT_ID ?? "11111111-1111-4111-8111-111111111111";
const SINCE = process.env.SINCE ?? null;
const EMIT_JSON = process.env.JSON === "1";
const OUT_PATH = process.env.OUT ?? null;
const PAGE_SIZE = 1000;

// Personas generated by the live channel-test scripts. Sourced from
// scripts/diagnose-test-booking-pollution.mts so the two stay recognisable.
const TEST_EMAIL_RE =
  /^(sarah\.sms|david\.wp|alice\.wp|tom\.webchat|mark\.sms|priya\.web|linda\.voice|james\.voice|john\.smith)\.\d+@test\.com$/i;
const TEST_EMAIL_DOMAIN_RE = /@(test|example)\.(com|org|net|local)$/i;
const TEST_FULL_NAME_RE =
  /^(Sarah Brown|David Patel|Alice Thompson|Tom Hughes|Mark O'?Connor|Priya Shah|Linda|James|John Smith|Test .*|.* Test)$/i;
// Twilio's documented magic numbers — never a real customer.
const TWILIO_TEST_NUMBER_RE = /^\+1500555\d{4}$/;

function mask(value) {
  if (typeof value !== "string" || value.length === 0) return null;
  if (value.includes("@")) {
    const [local, domain] = value.split("@");
    return `${local.slice(0, 2)}***@${domain}`;
  }
  if (value.length <= 4) return "***";
  return `${value.slice(0, 2)}***${value.slice(-2)}`;
}

function reasonsForCustomer(row) {
  const reasons = [];
  if (row.is_test) reasons.push("is_test flag");
  if (row.is_demo) reasons.push("is_demo flag");
  if (row.email && TEST_EMAIL_RE.test(row.email)) reasons.push("channel-test persona email");
  else if (row.email && TEST_EMAIL_DOMAIN_RE.test(row.email)) reasons.push("test/example email domain");
  if (row.full_name && TEST_FULL_NAME_RE.test(row.full_name)) reasons.push("channel-test persona name");
  if (row.phone && TWILIO_TEST_NUMBER_RE.test(row.phone)) reasons.push("Twilio magic test number");
  return reasons;
}

function reasonsForGeneric(row) {
  const reasons = [];
  if (row.is_test) reasons.push("is_test flag");
  if (row.is_demo) reasons.push("is_demo flag");
  if (typeof row.source === "string" && /channel[_-]?test|smoke|e2e/i.test(row.source)) {
    reasons.push(`source=${row.source}`);
  }
  return reasons;
}

async function fetchAll(admin, table, columns) {
  const rows = [];
  for (let offset = 0; ; offset += PAGE_SIZE) {
    let query = admin
      .schema("crm")
      .from(table)
      .select(columns)
      .eq("tenant_id", TENANT_ID)
      .order("created_at", { ascending: true })
      .range(offset, offset + PAGE_SIZE - 1);
    if (SINCE) {
      query = query.gte("created_at", SINCE);
    }
    const { data, error } = await query;
    if (error) throw new Error(`${table}: ${error.message}`);
    rows.push(...(data ?? []));
    if ((data ?? []).length < PAGE_SIZE) break;
  }
  return rows;
}

async function main() {
  const { supabaseUrl, serviceRoleKey } = requireCrmScriptConfig(true);
  const admin = createClient(supabaseUrl, serviceRoleKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  console.log("audit-test-crm-records.mjs — READ ONLY, no writes");
  console.log(`  Supabase: ${supabaseUrl}`);
  console.log(`  Tenant:   ${TENANT_ID}`);
  console.log(`  Since:    ${SINCE ?? "(all time)"}`);
  console.log("");

  const customers = await fetchAll(
    admin,
    "customers",
    "id, full_name, phone, email, is_test, is_demo, archived, record_deleted_at, created_at",
  );
  const leads = await fetchAll(
    admin,
    "leads",
    "id, customer_id, status, source, is_test, is_demo, record_deleted_at, created_at",
  );
  const jobs = await fetchAll(admin, "jobs", "id, customer_id, lead_id, status, is_test, is_demo, created_at");
  const appointments = await fetchAll(
    admin,
    "appointments",
    "id, customer_id, lead_id, job_id, status, starts_at, is_test, created_at",
  );

  const candidates = { customers: [], leads: [], jobs: [], appointments: [] };

  for (const row of customers) {
    const reasons = reasonsForCustomer(row);
    if (reasons.length === 0) continue;
    candidates.customers.push({
      id: row.id,
      name: mask(row.full_name),
      email: mask(row.email),
      phone: mask(row.phone),
      created_at: row.created_at,
      already_deleted: Boolean(row.record_deleted_at),
      reasons,
    });
  }

  // A lead/job/appointment inherits suspicion from its customer: a test customer's
  // enquiries are test enquiries even when the child row carries no flag of its own.
  const testCustomerIds = new Set(candidates.customers.map((row) => row.id));

  for (const row of leads) {
    const reasons = reasonsForGeneric(row);
    if (row.customer_id && testCustomerIds.has(row.customer_id)) reasons.push("linked to a candidate customer");
    if (reasons.length === 0) continue;
    candidates.leads.push({
      id: row.id,
      customer_id: row.customer_id,
      status: row.status,
      created_at: row.created_at,
      already_deleted: Boolean(row.record_deleted_at),
      reasons,
    });
  }

  for (const row of jobs) {
    const reasons = reasonsForGeneric(row);
    if (row.customer_id && testCustomerIds.has(row.customer_id)) reasons.push("linked to a candidate customer");
    if (reasons.length === 0) continue;
    candidates.jobs.push({ id: row.id, status: row.status, created_at: row.created_at, reasons });
  }

  for (const row of appointments) {
    const reasons = reasonsForGeneric(row);
    if (row.customer_id && testCustomerIds.has(row.customer_id)) reasons.push("linked to a candidate customer");
    if (reasons.length === 0) continue;
    candidates.appointments.push({
      id: row.id,
      status: row.status,
      starts_at: row.starts_at,
      created_at: row.created_at,
      reasons,
    });
  }

  const totals = {
    customers: { scanned: customers.length, candidates: candidates.customers.length },
    leads: { scanned: leads.length, candidates: candidates.leads.length },
    jobs: { scanned: jobs.length, candidates: candidates.jobs.length },
    appointments: { scanned: appointments.length, candidates: candidates.appointments.length },
  };

  for (const [table, counts] of Object.entries(totals)) {
    console.log(`${table.padEnd(13)} ${String(counts.candidates).padStart(5)} candidate / ${counts.scanned} scanned`);
  }
  console.log("");

  // Reason histogram — the fastest way for a reviewer to see WHY rows were
  // flagged, and to spot a rule that is over-matching.
  const histogram = new Map();
  for (const list of Object.values(candidates)) {
    for (const row of list) {
      for (const reason of row.reasons) {
        histogram.set(reason, (histogram.get(reason) ?? 0) + 1);
      }
    }
  }
  console.log("Reasons:");
  for (const [reason, count] of [...histogram.entries()].sort((a, b) => b[1] - a[1])) {
    console.log(`  ${String(count).padStart(5)}  ${reason}`);
  }
  console.log("");

  const upcoming = candidates.appointments.filter(
    (row) => row.starts_at && new Date(row.starts_at).getTime() > Date.now(),
  );
  if (upcoming.length > 0) {
    console.log(
      `WARNING: ${upcoming.length} candidate appointment(s) are in the FUTURE. Confirm none is a real customer before deleting.`,
    );
    console.log("");
  }

  const payload = { tenantId: TENANT_ID, since: SINCE, generatedAt: new Date().toISOString(), totals, candidates };
  if (OUT_PATH) {
    fs.writeFileSync(OUT_PATH, JSON.stringify(payload, null, 2));
    console.log(`Candidate list written to ${OUT_PATH}`);
  }
  if (EMIT_JSON) {
    console.log(JSON.stringify(payload, null, 2));
  }

  console.log("");
  console.log("No rows were changed. Review the candidates, then approve a deletion set.");
}

main().catch((error) => {
  console.error("FAILED:", error?.message ?? error);
  process.exit(1);
});
